/* Bitmap decoded from Braille data. */
#define BMP_W (DRAGON_COLS * 2)
#define BMP_H (DRAGON_ROWS * 4)
static UINT8 g_Bmp[(BMP_W * BMP_H + 7) / 8];
static BOOLEAN g_BmpReady = FALSE;

static BOOLEAN BrailleDotSet(UINT8 pattern, UINTN x, UINTN y)
{
    static const UINT8 bits[4][2] = {
        {0, 3},
        {1, 4},
        {2, 5},
        {6, 7}
    };

    return (pattern & (1U << bits[y][x])) != 0;
}

static void DecodeDragon(void)
{
    if (g_BmpReady) return;

    UINTN cellX = 0;
    UINTN cellY = 0;
    (void)DRAGON;

    gBS->SetMem(g_Bmp, sizeof(g_Bmp), 0);

    for (UINTN i = 0; i < sizeof(DRAGON_ART) / sizeof(DRAGON_ART[0]); i++)
    {
        DragonRun run = DRAGON_ART[i];
        if (run.Count == 0)
        {
            cellX = 0;
            cellY++;
            continue;
        }

        for (UINTN repeat = 0; repeat < run.Count; repeat++)
        {
            for (UINTN y = 0; y < 4; y++)
            {
                for (UINTN x = 0; x < 2; x++)
                {
                    UINTN absX = cellX * 2 + x;
                    UINTN absY = cellY * 4 + y;
                    if (!BrailleDotSet(run.Pattern, x, y) || absX >= BMP_W || absY >= BMP_H)
                        continue;

                    UINTN bi = absY * BMP_W + absX;
                    g_Bmp[bi / 8] |= (1 << (7 - (bi % 8)));
                }
            }

            cellX++;
        }
    }

    g_BmpReady = TRUE;
}

