static void ReadMenuInput(UINTN* selected, UINTN count, CHAR16* key, BOOLEAN* activate)
{
    UINTN index = 0;

    *key = 0;
    *activate = FALSE;

    gBS->WaitForEvent(1, &gST->ConIn->WaitForKey, &index);

    EFI_INPUT_KEY input;
    if (EFI_ERROR(gST->ConIn->ReadKeyStroke(gST->ConIn, &input)))
        return;

    *key = input.UnicodeChar;
    if (input.ScanCode == RD_SCAN_UP || input.ScanCode == RD_SCAN_LEFT)
        *selected = (*selected == 0) ? count - 1 : *selected - 1;
    else if (input.ScanCode == RD_SCAN_DOWN || input.ScanCode == RD_SCAN_RIGHT)
        *selected = (*selected + 1) % count;
    else if (input.ScanCode == RD_SCAN_ESC)
        *selected = count - 1;
    else if (input.UnicodeChar == L'\r')
        *activate = TRUE;
}

