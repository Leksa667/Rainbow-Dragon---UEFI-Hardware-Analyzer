// ── Draw dragon → framebuffer (pixel‑perfect) ──────────────────
static void PixelFromAttr(UINTN attr, GOP_PX *px)
{
    px->A = 0;

    switch (attr) {
        case 0x04: px->R=170;px->G=  0;px->B=  0;break; case 0x06: px->R=170;px->G= 85;px->B=  0;break;
        case 0x0E: px->R=255;px->G=255;px->B= 85;break; case 0x0A: px->R= 85;px->G=255;px->B= 85;break;
        case 0x02: px->R=  0;px->G=170;px->B=  0;break; case 0x0B: px->R= 85;px->G=255;px->B=255;break;
        case 0x03: px->R=  0;px->G=170;px->B=170;break; case 0x09: px->R= 85;px->G=170;px->B=255;break;
        case 0x01: px->R=  0;px->G=  0;px->B=170;break; case 0x0D: px->R=255;px->G= 85;px->B=255;break;
        case 0x05: px->R=170;px->G=  0;px->B=170;break; case 0x0C: px->R=255;px->G= 85;px->B= 85;break;
        default:   px->R=170;px->G=170;px->B=170;break;
    }
}

static void FillRect(GOP *gop, GOP_PX *px, UINTN x, UINTN y, UINTN w, UINTN h)
{
    gop->Blt(gop, px, 0, 0, 0, x, y, w, h, 0);
}

static BOOLEAN DrawViaFB(void)
{
    EFI_GUID guid = GOP_GUID;
    GOP *gop = NULL;
    EFI_STATUS st = gBS->LocateProtocol(&guid, NULL, (void**)&gop);

    if (EFI_ERROR(st) || !gop || !gop->Mode || !gop->Mode->Info || !gop->Blt)
        return FALSE;

    UINT32 sw = gop->Mode->Info->HRes;
    UINT32 sh = gop->Mode->Info->VRes;

    UINT32 scaleX = sw / (BMP_W + 24);
    UINT32 scaleY = (sh / 3) / BMP_H;
    UINT32 sc = (scaleX < scaleY) ? scaleX : scaleY;
    if (sc < 2) sc = 2;
    if (sc > 4) sc = 4;

    UINT32 iw = BMP_W * sc, ih = BMP_H * sc;
    UINT32 sx = (sw > iw) ? (sw - iw) / 2 : 0;
    UINT32 sy = 10;

    GOP_PX black = {0, 0, 0, 0};
    FillRect(gop, &black, 0, 0, sw, ih + sy + 8);

    for (UINTN dy = 0; dy < BMP_H; dy++)
    {
        UINTN line = dy / 4;
        UINTN attr = RAINBOW[Wrap(line)];
        GOP_PX color;
        PixelFromAttr(attr, &color);

        for (UINTN dx = 0; dx < BMP_W; dx++)
        {
            UINTN bi = dy * BMP_W + dx;
            if (!((g_Bmp[bi/8] >> (7 - bi%8)) & 1))
                continue;

            FillRect(gop, &color, sx + dx * sc, sy + dy * sc, sc, sc);
        }
    }

    return TRUE;
}

